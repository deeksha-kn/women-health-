"""
Generates a PDF report for a single prediction record (text or image),
containing user info, the prediction result, confidence score, timestamp,
and condition-appropriate recommendations.
"""
from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.core.config import settings
from app.models.acne_record import AcneImageRecord
from app.models.prediction_history import PredictionHistory
from app.models.user import User

DISCLAIMER = (
    "This report is generated by an automated prediction system and is for "
    "informational purposes only. It is not a medical diagnosis. Please "
    "consult a qualified healthcare professional for proper evaluation, "
    "diagnosis, and treatment."
)

_RECOMMENDATIONS_BY_CONDITION = {
    "pcos": [
        "Consider a low glycemic index diet and regular physical activity.",
        "Discuss hormonal panel testing with a gynecologist or endocrinologist.",
        "Track your menstrual cycle and symptoms over time.",
    ],
    "pcod": [
        "Maintain a balanced diet and regular exercise routine.",
        "Consider discussing cycle irregularities with a gynecologist.",
        "Monitor weight, energy levels, and cycle patterns over time.",
    ],
    "thyroid": [
        "Discuss a full thyroid panel (TSH, T3, T4) with your doctor if you haven't had one recently.",
        "Note any changes in weight, energy, heart rate, or temperature sensitivity.",
        "Thyroid conditions are very manageable with proper medical care once diagnosed.",
    ],
}

_RECOMMENDATIONS_BY_SEVERITY = {
    "low": ["Continue your current skincare routine.", "Monitor for any changes over time."],
    "moderate": [
        "Consider consulting a dermatologist for a tailored treatment plan.",
        "Avoid picking or popping affected areas to reduce scarring risk.",
    ],
    "high": [
        "We recommend consulting a dermatologist promptly for evaluation.",
        "Avoid harsh scrubbing or picking, which can worsen inflammation.",
    ],
}


def _build_styles():
    styles = getSampleStyleSheet()
    styles.add(
        ParagraphStyle(
            name="ReportTitle",
            parent=styles["Title"],
            fontSize=20,
            spaceAfter=6,
        )
    )
    styles.add(
        ParagraphStyle(
            name="SectionHeading",
            parent=styles["Heading2"],
            spaceBefore=14,
            spaceAfter=6,
            textColor=colors.HexColor("#9d174d"),
        )
    )
    styles.add(
        ParagraphStyle(
            name="Disclaimer",
            parent=styles["Normal"],
            fontSize=8,
            textColor=colors.grey,
        )
    )
    return styles


def _info_table(rows: list[tuple[str, str]]) -> Table:
    table = Table(rows, colWidths=[1.8 * inch, 4.2 * inch])
    table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("LINEBELOW", (0, 0), (-1, -2), 0.5, colors.HexColor("#e5e7eb")),
            ]
        )
    )
    return table


def generate_text_prediction_report(user: User, record: PredictionHistory) -> str:
    Path(settings.REPORT_DIR).mkdir(parents=True, exist_ok=True)
    out_path = Path(settings.REPORT_DIR) / f"report_{record.id}.pdf"

    styles = _build_styles()
    doc = SimpleDocTemplate(str(out_path), pagesize=letter, topMargin=0.7 * inch, bottomMargin=0.7 * inch)
    story = []

    story.append(Paragraph("Women's Health Prediction Report", styles["ReportTitle"]))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Generated {datetime.now().strftime('%B %d, %Y at %I:%M %p')}", styles["Normal"]))

    story.append(Paragraph("Patient Information", styles["SectionHeading"]))
    story.append(
        _info_table(
            [
                ["Name", user.name],
                ["Email", user.email],
                ["Phone", user.phone or "Not provided"],
            ]
        )
    )

    story.append(Paragraph("Prediction Result", styles["SectionHeading"]))
    story.append(
        _info_table(
            [
                ["Condition", record.prediction_type.upper()],
                ["Model used", record.model_variant],
                ["Result", record.prediction_result],
                ["Confidence", f"{record.confidence_score:.1f}%"],
                ["Date & time", record.created_at.strftime("%B %d, %Y at %I:%M %p")],
            ]
        )
    )

    if record.probabilities:
        story.append(Paragraph("Full Probability Breakdown", styles["SectionHeading"]))
        prob_rows = [["Class", "Probability"]] + [
            [label, f"{p * 100:.1f}%"] for label, p in record.probabilities.items()
        ]
        prob_table = Table(prob_rows, colWidths=[3 * inch, 3 * inch])
        prob_table.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#fdf2f8")),
                    ("FONTSIZE", (0, 0), (-1, -1), 10),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ("TOPPADDING", (0, 0), (-1, -1), 6),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e5e7eb")),
                ]
            )
        )
        story.append(prob_table)

    story.append(Paragraph("Recommendations", styles["SectionHeading"]))
    recs = _RECOMMENDATIONS_BY_CONDITION.get(record.prediction_type, [])
    for rec in recs:
        story.append(Paragraph(f"&bull; {rec}", styles["Normal"]))

    story.append(Spacer(1, 18))
    story.append(Paragraph(DISCLAIMER, styles["Disclaimer"]))

    doc.build(story)
    return str(out_path)


def generate_image_prediction_report(user: User, record: AcneImageRecord) -> str:
    Path(settings.REPORT_DIR).mkdir(parents=True, exist_ok=True)
    out_path = Path(settings.REPORT_DIR) / f"report_{record.id}.pdf"

    styles = _build_styles()
    doc = SimpleDocTemplate(str(out_path), pagesize=letter, topMargin=0.7 * inch, bottomMargin=0.7 * inch)
    story = []

    story.append(Paragraph("Acne Severity Analysis Report", styles["ReportTitle"]))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Generated {datetime.now().strftime('%B %d, %Y at %I:%M %p')}", styles["Normal"]))

    story.append(Paragraph("Patient Information", styles["SectionHeading"]))
    story.append(
        _info_table(
            [
                ["Name", user.name],
                ["Email", user.email],
                ["Phone", user.phone or "Not provided"],
            ]
        )
    )

    story.append(Paragraph("Analysis Result", styles["SectionHeading"]))
    story.append(
        _info_table(
            [
                ["Severity", record.severity_result.capitalize()],
                ["Confidence", f"{record.confidence_score:.1f}%"],
                ["Date & time", record.created_at.strftime("%B %d, %Y at %I:%M %p")],
            ]
        )
    )

    if record.model_degraded:
        story.append(Spacer(1, 10))
        story.append(
            Paragraph(
                "<b>Notice:</b> This image analysis model is currently flagged as "
                "unreliable — it has been found to produce nearly identical results "
                "regardless of the image submitted. Treat this result as a placeholder, "
                "not an actual severity assessment.",
                ParagraphStyle(
                    name="DegradedWarning",
                    parent=styles["Normal"],
                    textColor=colors.HexColor("#b91c1c"),
                    backColor=colors.HexColor("#fef2f2"),
                    borderPadding=8,
                ),
            )
        )

    story.append(Paragraph("Recommendations", styles["SectionHeading"]))
    recs = _RECOMMENDATIONS_BY_SEVERITY.get(record.severity_result.lower(), [])
    for rec in recs:
        story.append(Paragraph(f"&bull; {rec}", styles["Normal"]))

    story.append(Spacer(1, 18))
    story.append(Paragraph(DISCLAIMER, styles["Disclaimer"]))

    doc.build(story)
    return str(out_path)
