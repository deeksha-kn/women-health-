'use client';

import { Button } from '@/components/ui/button';
import { useAuth } from '@/lib/auth-context';
import { reportApi } from '@/lib/api';
import type { CombinedResult } from '@/app/page';
import { useState } from 'react';
import Link from 'next/link';

interface PredictionResultsProps {
  combinedResult: CombinedResult;
  onSaveResults: () => void;
  onNewAnalysis: () => void;
}

const RECOMMENDATIONS: Record<string, string[]> = {
  pcos: [
    'Consider a low glycemic index diet with whole grains and vegetables.',
    'Regular physical activity (30 min most days) helps with hormonal balance.',
    'Consult a gynecologist or endocrinologist for a hormonal panel.',
    'Track your menstrual cycle and symptoms over time.',
  ],
  pcod: [
    'Maintain a balanced, anti-inflammatory diet.',
    'Discuss cycle irregularities with a gynecologist.',
    'Monitor weight, energy levels, and period patterns.',
    'Lifestyle changes can significantly reduce PCOD symptoms.',
  ],
  thyroid: [
    'Discuss a full thyroid panel (TSH, T3, T4) with your doctor.',
    'Thyroid conditions are highly manageable with proper treatment.',
    'Note any changes in weight, energy, heart rate, or temperature sensitivity.',
    'Iodine-rich foods (seafood, dairy) support thyroid health.',
  ],
};

const conditionLabel: Record<string, string> = {
  pcos: 'PCOS (Polycystic Ovary Syndrome)',
  pcod: 'PCOD (Polycystic Ovarian Disease)',
  thyroid: 'Thyroid Function',
};

export function PredictionResults({ combinedResult, onSaveResults, onNewAnalysis }: PredictionResultsProps) {
  const { isAuthenticated } = useAuth();
  const { textResults, imageResult } = combinedResult;
  const [downloadingId, setDownloadingId] = useState<string | null>(null);

  const getResultColor = (prediction: string, condition: string) => {
    const p = prediction.toLowerCase();
    if (condition === 'pcos' || condition === 'pcod') {
      if (p.includes('no ')) return { bg: 'bg-green-50 border-green-200', text: 'text-green-700', label: 'Unlikely' };
      return { bg: 'bg-red-50 border-red-200', text: 'text-red-700', label: 'Possible — consult a doctor' };
    }
    if (condition === 'thyroid') {
      if (p === 'normal' || p === 'negative') return { bg: 'bg-green-50 border-green-200', text: 'text-green-700', label: 'Normal range' };
      if (p === 'hypothyroid') return { bg: 'bg-yellow-50 border-yellow-200', text: 'text-yellow-700', label: 'Possible hypothyroid' };
      if (p === 'hyperthyroid') return { bg: 'bg-orange-50 border-orange-200', text: 'text-orange-700', label: 'Possible hyperthyroid' };
      return { bg: 'bg-gray-50 border-gray-200', text: 'text-gray-700', label: 'Other' };
    }
    return { bg: 'bg-gray-50 border-gray-200', text: 'text-gray-700', label: prediction };
  };

  const severityColors: Record<string, { bg: string; text: string }> = {
    low: { bg: 'bg-green-50 border-green-200', text: 'text-green-700' },
    moderate: { bg: 'bg-yellow-50 border-yellow-200', text: 'text-yellow-700' },
    high: { bg: 'bg-red-50 border-red-200', text: 'text-red-700' },
  };

  const handleDownload = async (id: string, condition: string) => {
    setDownloadingId(id);
    try {
      await reportApi.download(id, `healthhub_${condition}_report.pdf`);
    } catch (err) {
      console.error('Report download failed', err);
    } finally {
      setDownloadingId(null);
    }
  };

  if (textResults.length === 0 && !imageResult) {
    return (
      <div className="max-w-3xl mx-auto text-center py-20">
        <div className="text-4xl mb-4">⚠️</div>
        <h2 className="text-xl font-bold text-foreground mb-2">No results to display</h2>
        <p className="text-gray-500 mb-6">All predictions failed. Please check your connection and try again.</p>
        <Button onClick={onNewAnalysis} className="bg-primary text-white px-8">Try Again</Button>
      </div>
    );
  }

  return (
    <div className="max-w-5xl mx-auto space-y-8">
      {/* Header */}
      <div className="text-center mb-8">
        <p className="text-primary font-semibold text-sm uppercase tracking-wide mb-4">YOUR RESULTS</p>
        <h2 className="text-4xl font-bold text-foreground mb-3">Your Analysis Complete</h2>
        <p className="text-gray-600 text-lg">AI-powered screening based on your health data</p>
      </div>

      {/* Disclaimer */}
      <div className="bg-blue-50 border border-blue-200 rounded-xl p-6">
        <p className="text-sm text-blue-900">
          <strong>Important:</strong> These results are generated by machine learning models for screening purposes only.
          They are <strong>not medical diagnoses</strong>. Confidence scores reflect the model's certainty about its
          classification, not the probability you actually have the condition. Please consult a qualified healthcare
          professional for proper evaluation and diagnosis.
        </p>
      </div>

      {/* Text prediction results */}
      {textResults.map((result) => {
        const colors = getResultColor(result.prediction, result.condition);
        const recs = RECOMMENDATIONS[result.condition] ?? [];
        const isPositive = !result.prediction.toLowerCase().startsWith('no') && result.prediction.toLowerCase() !== 'normal' && result.prediction.toLowerCase() !== 'negative';

        return (
          <div key={result.id} className={`border-2 rounded-2xl p-6 ${colors.bg}`}>
            <div className="flex items-start justify-between gap-6 mb-5">
              <div className="flex-1">
                <h3 className="text-2xl font-bold text-foreground mb-1">
                  {conditionLabel[result.condition] ?? result.condition.toUpperCase()}
                </h3>
                <p className={`font-semibold ${colors.text}`}>{colors.label}</p>
                <p className="text-xs text-gray-500 mt-1">Model: {result.model_variant}</p>
              </div>
              <div className="text-right">
                <div className="text-4xl font-bold text-foreground">{result.confidence_score.toFixed(1)}</div>
                <div className="text-sm text-gray-500">% confidence</div>
              </div>
            </div>

            {/* Confidence bar */}
            <div className="mb-5">
              <div className="w-full bg-white/60 rounded-full h-2 overflow-hidden">
                <div
                  className={`h-full transition-all ${isPositive ? 'bg-red-400' : 'bg-green-400'}`}
                  style={{ width: `${result.confidence_score}%` }}
                />
              </div>
            </div>

            {/* Probability breakdown */}
            <div className="bg-white/60 rounded-xl p-4 mb-5">
              <h4 className="text-xs font-semibold text-gray-500 uppercase tracking-wide mb-3">Probability Breakdown</h4>
              <div className="space-y-2">
                {Object.entries(result.probabilities).map(([label, prob]) => (
                  <div key={label} className="flex items-center gap-3">
                    <span className="text-sm text-gray-700 w-32 shrink-0">{label}</span>
                    <div className="flex-1 bg-gray-200 rounded-full h-1.5 overflow-hidden">
                      <div className="h-full bg-primary/60 rounded-full" style={{ width: `${(prob * 100).toFixed(1)}%` }} />
                    </div>
                    <span className="text-sm text-gray-600 w-12 text-right">{(prob * 100).toFixed(1)}%</span>
                  </div>
                ))}
              </div>
            </div>

            {/* Recommendations */}
            {recs.length > 0 && (
              <div className="space-y-2 pt-4 border-t border-current/10 mb-4">
                <h4 className="text-sm font-semibold text-foreground">What You Can Do:</h4>
                <ul className="space-y-1.5">
                  {recs.map((rec, i) => (
                    <li key={i} className="text-sm text-foreground flex items-start gap-2">
                      <span className="text-primary font-bold mt-0.5">✓</span>
                      <span>{rec}</span>
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Download report */}
            {isAuthenticated && (
              <button
                onClick={() => handleDownload(result.id, result.condition)}
                disabled={downloadingId === result.id}
                className="text-xs border border-current/20 hover:bg-white/40 px-4 py-2 rounded-lg transition-colors disabled:opacity-50"
              >
                {downloadingId === result.id ? 'Generating PDF…' : '↓ Download PDF Report'}
              </button>
            )}
          </div>
        );
      })}

      {/* Image prediction result */}
      {imageResult && (
        <div className={`border-2 rounded-2xl p-6 ${severityColors[imageResult.severity.toLowerCase()]?.bg ?? 'bg-gray-50 border-gray-200'}`}>
          <div className="flex items-start justify-between gap-6 mb-5">
            <div>
              <h3 className="text-2xl font-bold text-foreground mb-1">Acne Severity Analysis</h3>
              <p className={`font-semibold ${severityColors[imageResult.severity.toLowerCase()]?.text ?? 'text-gray-700'}`}>
                {imageResult.severity.charAt(0).toUpperCase() + imageResult.severity.slice(1)} Severity
              </p>
            </div>
            <div className="text-right">
              <div className="text-4xl font-bold text-foreground">{imageResult.confidence_score.toFixed(1)}</div>
              <div className="text-sm text-gray-500">% confidence</div>
            </div>
          </div>

          {/* Degraded model warning */}
          {imageResult.model_degraded && (
            <div className="bg-yellow-50 border border-yellow-200 text-yellow-800 text-sm rounded-lg px-4 py-3 mb-5">
              <strong>⚠️ Notice:</strong> {imageResult.warning}
            </div>
          )}

          {/* Probability breakdown */}
          <div className="bg-white/60 rounded-xl p-4 mb-5">
            <h4 className="text-xs font-semibold text-gray-500 uppercase tracking-wide mb-3">Severity Breakdown</h4>
            <div className="space-y-2">
              {Object.entries(imageResult.probabilities).map(([label, prob]) => (
                <div key={label} className="flex items-center gap-3">
                  <span className="text-sm text-gray-700 w-24 shrink-0 capitalize">{label}</span>
                  <div className="flex-1 bg-gray-200 rounded-full h-1.5 overflow-hidden">
                    <div className="h-full bg-primary/60 rounded-full" style={{ width: `${(prob * 100).toFixed(1)}%` }} />
                  </div>
                  <span className="text-sm text-gray-600 w-12 text-right">{(prob * 100).toFixed(1)}%</span>
                </div>
              ))}
            </div>
          </div>

          {isAuthenticated && (
            <button
              onClick={() => handleDownload(imageResult.id, 'acne')}
              disabled={downloadingId === imageResult.id}
              className="text-xs border border-current/20 hover:bg-white/40 px-4 py-2 rounded-lg transition-colors disabled:opacity-50"
            >
              {downloadingId === imageResult.id ? 'Generating PDF…' : '↓ Download PDF Report'}
            </button>
          )}
        </div>
      )}

      {/* Action buttons */}
      <div className="flex flex-col sm:flex-row gap-4 pt-4">
        {isAuthenticated ? (
          <Button onClick={onSaveResults} className="flex-1 bg-primary hover:bg-primary/90 text-white py-3 text-base rounded-lg">
            Done — Go to Dashboard
          </Button>
        ) : (
          <div className="flex-1 bg-primary/10 border border-primary/20 rounded-xl p-4 text-sm text-primary text-center">
            <strong>Sign up to save your results</strong> and download PDF reports.
            <Link href="/" className="block mt-2 underline text-xs">Sign up for free →</Link>
          </div>
        )}
        <Button onClick={onNewAnalysis} variant="outline" className="flex-1 py-3 text-base rounded-lg border-2">
          New Analysis
        </Button>
      </div>

      {/* Next steps */}
      <div className="bg-gray-50 border border-gray-200 rounded-2xl p-8">
        <h3 className="text-xl font-bold text-foreground mb-5">Recommended Next Steps</h3>
        <div className="space-y-3">
          {[
            'Review the recommendations specific to your results above.',
            'Schedule appointments with relevant healthcare specialists.',
            'Consider getting comprehensive hormone and blood testing.',
            'Track changes in your symptoms and lifestyle over time.',
          ].map((step, i) => (
            <p key={i} className="text-sm text-gray-700 flex items-start gap-3">
              <span className="font-semibold text-primary min-w-fit">{i + 1}.</span>
              <span>{step}</span>
            </p>
          ))}
        </div>
      </div>
    </div>
  );
}
